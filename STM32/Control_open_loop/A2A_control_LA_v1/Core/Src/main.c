  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_3, 0);
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, 0);

  HAL_Delay(5);              // dead-time corto opcional
  if (str == 'e' || pct == 0) return;

  /* Adelante: 'b' */
